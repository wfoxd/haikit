#!/usr/bin/env node
/**
 * Builds @haikit/client's stylesheet, packages/client/src/hai.css: the
 * hand-written rules in packages/client/styles/hai.css, then the `hai:`
 * utilities that styles/utilities.css compiles from src/classes.js.
 *
 *   npm run build:css
 *
 * The output is committed, because the no-bundler path serves src/ as it is.
 * csstest fails when it is out of date with what this would write.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, optimize } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const STYLES = join(ROOT, "packages/client/styles");
export const OUT = join(ROOT, "packages/client/src/hai.css");

const NOTE = "/* Generated by scripts/build-css.mjs from packages/client/styles in HaiKIT's repo: edit those, then npm run build:css. */\n\n";

/** The stylesheet as the build would write it now. */
export async function buildHaiCss() {
  const input = join(STYLES, "utilities.css");
  const compiler = await compile(readFileSync(input, "utf8"), { base: STYLES, from: input, onDependency() {} });
  // the files its @source names, and nothing around them
  const candidates = new Scanner({ sources: compiler.sources }).scan();
  // nesting flattened and prefixes added for Tailwind's browser targets
  const utilities = optimize(compiler.build(candidates), { file: input }).code.trim();
  const rules = readFileSync(join(STYLES, "hai.css"), "utf8");
  // Tailwind's licence banner comes out even with no classes to compile
  const any = utilities.replace(/^\/\*![^]*?\*\/\s*/, "") !== "";
  return NOTE + rules + (any ? `\n/* ── utilities, from src/classes.js ─────────────────────────────────── */\n\n${utilities}\n` : "");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await buildHaiCss());
  console.log(`wrote ${OUT.slice(ROOT.length + 1)}`);
}
